#!/usr/bin/env node
/**
 * Pins every @carbon/* package to a single release set.
 *
 *   node scripts/use-carbon.mjs --tag v12-alpha
 *   node scripts/use-carbon.mjs --ref v12.0.0-alpha.5
 *   node scripts/use-carbon.mjs --tarballs ./carbon-tarballs
 *   node scripts/use-carbon.mjs --tag v12-alpha --react 18
 *   node scripts/use-carbon.mjs --release carbon-release.json --react 18
 *
 * --tag       npm dist-tag, resolved per package
 * --ref       upstream git ref; versions are read from each package.json at
 *             that ref, which is the exact set a release published
 * --tarballs  directory of `yarn pack` output, for testing unpublished commits
 * --release   a carbon-release.json written by an earlier run, so separate CI
 *             jobs test the exact same set
 * --git-ref   upstream commit or tag the packages were built from; found
 *             automatically for --tag, required context for --tarballs
 * --react     React major to test against (default: 19)
 *
 * Writes `carbon-release.json` and the Yarn catalog in `.yarnrc.yml`, which
 * every workspace references with `catalog:`. Only direct dependencies are
 * pinned: transitive @carbon/* dependencies resolve from each package's
 * declared ranges, the same way they do for consumers, so mismatched or
 * duplicated internal versions show up in the install instead of being hidden.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { parseArgs } from 'node:util';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(
  await fs.readFile(path.join(root, 'carbon.config.json'), 'utf8')
);

const YARNRC_HEADER = `# Generated by scripts/use-carbon.mjs. Edit settings there, not here.
nodeLinker: node-modules
enableTelemetry: false
`;

const REACT_VERSIONS = {
  18: {
    react: '^18.3.1',
    'react-dom': '^18.3.1',
    'react-is': '^18.3.1',
    '@types/react': '^18.3.0',
    '@types/react-dom': '^18.3.0',
  },
  19: {
    react: '^19.2.0',
    'react-dom': '^19.2.0',
    'react-is': '^19.2.0',
    '@types/react': '^19.2.0',
    '@types/react-dom': '^19.2.0',
  },
};

const { values } = parseArgs({
  options: {
    tag: { type: 'string' },
    ref: { type: 'string' },
    tarballs: { type: 'string' },
    release: { type: 'string' },
    'git-ref': { type: 'string' },
    react: { type: 'string', default: '19' },
  },
});

const modes = ['tag', 'ref', 'tarballs', 'release'].filter(
  (key) => values[key]
);
if (modes.length > 1) {
  fail('Pass only one of --tag, --ref, --tarballs, or --release');
}
if (modes.length === 0) {
  values.tag = config.defaultTag;
}
if (!REACT_VERSIONS[values.react]) {
  fail(`Unsupported --react ${values.react}`);
}

async function packument(name) {
  const response = await fetch(
    `https://registry.npmjs.org/${name.replace('/', '%2f')}`,
    { headers: { accept: 'application/vnd.npm.install-v1+json' } }
  );
  if (!response.ok) {
    throw new Error(`npm registry returned ${response.status} for ${name}`);
  }
  return response.json();
}

async function fromTag(tag) {
  const versions = {};
  const missing = [];
  await Promise.all(
    config.packages.map(async (pkg) => {
      const meta = await packument(pkg.name);
      const version = meta['dist-tags'][tag];
      if (version) {
        versions[pkg.name] = version;
      } else if (!pkg.optional) {
        missing.push(pkg.name);
      }
    })
  );
  if (missing.length) {
    fail(`No \`${tag}\` dist-tag for: ${missing.join(', ')}`);
  }
  return versions;
}

async function fromRef(ref) {
  const versions = {};
  const problems = [];
  await Promise.all(
    config.packages.map(async (pkg) => {
      const url = `https://raw.githubusercontent.com/${config.repository}/${ref}/packages/${pkg.dir}/package.json`;
      const response = await fetch(url);
      if (!response.ok) {
        if (!pkg.optional) {
          problems.push(`${pkg.name}: ${url} returned ${response.status}`);
        }
        return;
      }
      const { version, private: isPrivate } = await response.json();
      if (isPrivate) {
        return;
      }
      const meta = await packument(pkg.name);
      if (!meta.versions[version]) {
        if (!pkg.optional) {
          problems.push(`${pkg.name}@${version} is not published to npm`);
        }
        return;
      }
      versions[pkg.name] = version;
    })
  );
  if (problems.length) {
    throw new Error(
      `Release set for ${ref} is incomplete:\n  ${problems.join('\n  ')}`
    );
  }
  return versions;
}

async function fromTarballs(dir) {
  const absolute = path.resolve(dir);
  const files = await fs.readdir(absolute);
  const versions = {};
  for (const pkg of config.packages) {
    const prefix = pkg.name.replace('@', '').replace('/', '-') + '-';
    const file = files.find(
      (name) =>
        name.startsWith(prefix) &&
        name.endsWith('.tgz') &&
        /^\d/.test(name.slice(prefix.length))
    );
    if (file) {
      versions[pkg.name] = `file:${path.join(absolute, file)}`;
    } else if (!pkg.optional) {
      fail(`No tarball for ${pkg.name} in ${absolute}`);
    }
  }
  return versions;
}

const previous = values.release
  ? JSON.parse(await fs.readFile(path.resolve(values.release), 'utf8'))
  : null;

const source = previous
  ? previous.source
  : values.ref
    ? { type: 'ref', value: values.ref }
    : values.tarballs
      ? { type: 'tarballs', value: values.tarballs }
      : { type: 'tag', value: values.tag };

const versions = previous
  ? previous.packages
  : source.type === 'ref'
    ? await fromRef(source.value).catch((error) => fail(error.message))
    : source.type === 'tarballs'
      ? await fromTarballs(source.value)
      : await fromTag(source.value);

const sorted = Object.fromEntries(
  Object.entries(versions).sort(([a], [b]) => a.localeCompare(b))
);

const gitRef =
  values['git-ref'] ??
  (previous
    ? previous.gitRef
    : source.type === 'ref'
      ? source.value
      : source.type === 'tag'
        ? await findReleaseTag(sorted)
        : null);
if (!gitRef) {
  console.warn(
    'Could not match this release to an upstream git tag; v12 checks will run against every documented section.'
  );
}

await fs.writeFile(
  path.join(root, 'carbon-release.json'),
  JSON.stringify(
    { source, gitRef, react: Number(values.react), packages: sorted },
    null,
    2
  ) + '\n'
);

const catalog = { ...sorted, ...REACT_VERSIONS[values.react] };
await fs.writeFile(
  path.join(root, '.yarnrc.yml'),
  [
    YARNRC_HEADER,
    'catalog:',
    ...Object.entries(catalog).map(
      ([name, range]) => `  ${JSON.stringify(name)}: ${JSON.stringify(range)}`
    ),
    '',
  ].join('\n')
);

const packageJsonPath = path.join(root, 'package.json');
const packageJson = JSON.parse(await fs.readFile(packageJsonPath, 'utf8'));
packageJson.resolutions = Object.fromEntries(
  Object.entries(packageJson.resolutions ?? {}).filter(
    ([name]) => !name.startsWith('@carbon/')
  )
);
if (source.type === 'tarballs') {
  // Unpublished versions can only be reached transitively through overrides.
  Object.assign(packageJson.resolutions, sorted);
}
await fs.writeFile(
  packageJsonPath,
  JSON.stringify(packageJson, null, 2) + '\n'
);

console.log(`Carbon release from ${source.type} "${source.value}":`);
for (const [name, version] of Object.entries(sorted)) {
  console.log(`  ${name}@${version}`);
}
console.log(`React ${values.react}`);
console.log('Run `yarn install` to apply.');

/**
 * Finds the newest upstream release tag whose package versions match the
 * resolved set, so documentation and fixtures can be read at that commit.
 */
async function findReleaseTag(resolved) {
  const output = execFileSync(
    'git',
    [
      'ls-remote',
      '--tags',
      '--refs',
      `https://github.com/${config.repository}.git`,
      `${config.releaseTagPrefix}*`,
    ],
    { encoding: 'utf8' }
  );
  const tags = output
    .trim()
    .split('\n')
    .filter(Boolean)
    .map((line) => line.split('refs/tags/')[1])
    .sort((a, b) => b.localeCompare(a, undefined, { numeric: true }))
    .slice(0, 10);
  const probe =
    config.packages.find((pkg) => pkg.name === '@carbon/react') ??
    config.packages.find((pkg) => resolved[pkg.name]);
  for (const tag of tags) {
    const response = await fetch(
      `https://raw.githubusercontent.com/${config.repository}/${tag}/packages/${probe.dir}/package.json`
    );
    if (!response.ok) {
      continue;
    }
    const { version } = await response.json();
    if (version !== resolved[probe.name]) {
      continue;
    }
    const tagged = await fromRef(tag).catch(() => null);
    if (
      tagged &&
      Object.entries(resolved).every(([name, v]) => tagged[name] === v)
    ) {
      return tag;
    }
  }
  return null;
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
